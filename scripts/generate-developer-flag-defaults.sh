// Generated by scripts/generate-developer-flag-defaults.sh from
// wire-ios/Configuration/Developer-Flags.xcconfig — DO NOT EDIT.

/// Compile-time developer flag defaults, mirrored from Developer-Flags.xcconfig.
public enum DeveloperFlagsDefaults {

    /// Raw key/value pairs as declared in the xcconfig for the current build flavour.
    public static let values: [String: String] = [
$DICTIONARY    ]

    /// Returns whether the given xcconfig key is enabled (value is "1").
    public static func isEnabled(_ key: String) -> Bool {
        values[key] == "1"
    }
}
EOF

echo "✅ Generated $OUTPUT from Developer-Flags.xcconfig"
